package day_1;

// Increment and Decrement operators 

public class P5 {
	public static void main(String[] args) {
		int a=10;
		System.out.println(a);
		a++;
		System.out.println(a);
		System.out.println(a++);
		System.out.println(a);
		System.out.println(a--);
		System.out.println(a);
		System.out.println(--a);
	}

}
